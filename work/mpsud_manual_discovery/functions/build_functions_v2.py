def f(name, unit=None, kind='numeric', evidence='SECONDARY_TEXT', note=None):
    return {'name': name, 'kind': kind, 'unit': unit,
            'unit_status': 'EXPLICIT_IN_SOURCE' if unit else (
                'NOT_APPLICABLE' if kind in ('discrete', 'enum', 'text', 'address', 'count', 'date_time')
                else 'UNIT_NOT_PRINTED_OR_NOT_ESTABLISHED'),
            'evidence': evidence, 'note': note}


